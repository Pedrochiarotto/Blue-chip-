-- Blue Chip Poker — schema inicial para Supabase Postgres
-- Execute este arquivo no SQL Editor do projeto.

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  username text unique not null,
  password_hash text not null
);

create table if not exists public.content (
  key text primary key,
  value text not null
);

create table if not exists public.cards (
  id bigint generated by default as identity primary key,
  carousel text not null check (carousel in ('schedule', 'restaurant')),
  tag text not null default '',
  title text not null,
  description text not null default '',
  image_url text not null default '',
  link_url text not null default '',
  position integer not null default 0,
  active boolean not null default true
);

-- Mantém projetos existentes compatíveis ao executar novamente este arquivo.
alter table public.cards
  add column if not exists link_url text not null default '';

create table if not exists public.tournament (
  id integer primary key check (id = 1),
  data jsonb not null
);

create index if not exists cards_carousel_position_idx
  on public.cards (carousel, position, id);

-- O backend FastAPI acessará estas tabelas com a conexão privada do banco.
-- O acesso direto pelo navegador permanece bloqueado por padrão.
alter table public.users enable row level security;
alter table public.content enable row level security;
alter table public.cards enable row level security;
alter table public.tournament enable row level security;

-- Bucket público para flyers e imagens exibidas na landing page.
insert into storage.buckets (id, name, public)
values ('club-media', 'club-media', true)
on conflict (id) do update set public = excluded.public;
